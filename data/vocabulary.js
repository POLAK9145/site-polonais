export const themeKeys = Object.keys(vocabulary);

// Build a flat list of cards for the SRS module.
export function allCards() {
  const out = [];
  for (const key of themeKeys) {
    const theme = vocabulary[key];
    theme.words.forEach((w, i) => {
      out.push({
        id: `${key}:${i}:${w.pl}`,
        theme: key,
        themeLabel: theme.label,
        front: w.pl,
        back: w.fr,
      });
    });
  }
  return out;
}
